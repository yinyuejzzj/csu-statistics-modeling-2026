# 构建长格式面板数据
rows = []
for year in years:
    # 取最近可用年份数据（插值）
    avail_years = sorted(birth_rate.keys())
    
    def interp(data_dict, yr):
        keys = sorted(data_dict.keys())
        if yr in data_dict:
            return data_dict[yr]
        # 线性插值
        lo = max([k for k in keys if k <= yr], default=keys[0])
        hi = min([k for k in keys if k >= yr], default=keys[-1])
        if lo == hi:
            return {p: data_dict[lo].get(p, np.nan) for p in provinces}
        w = (yr - lo) / (hi - lo)
        result = {}
        for p in provinces:
            v_lo = data_dict[lo].get(p, np.nan)
            v_hi = data_dict[hi].get(p, np.nan)
            result[p] = v_lo + w * (v_hi - v_lo) if not (np.isnan(v_lo) or np.isnan(v_hi)) else np.nan
        return result

    br = interp(birth_rate, year)
    inc = interp(income, year)
    urb = interp(urbanization, year)

    for prov in provinces:
        rows.append({
            'province': prov,
            'year': year,
            'birth_rate': br.get(prov, np.nan),
            'income': inc.get(prov, np.nan),
            'urbanization': urb.get(prov, np.nan),
        })

